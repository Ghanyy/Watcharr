// ReactivateMatrixAccount creates a new Matrix account for reactivation since Dendrite doesn't support true reactivation
func ReactivateMatrixAccount(matrixUserID, newPassword string) (*SharedSecretRegistrationResponse, error) {
	errContext := map[string]interface{}{
		"matrix_user_id": matrixUserID,
	}
	
	// Extract the localpart from the Matrix user ID
	// Format: @localpart:server.name
	if !strings.HasPrefix(matrixUserID, "@") || !strings.Contains(matrixUserID, ":") {
		return nil, logAndReturnError("invalid_matrix_user_id", 
			fmt.Errorf("invalid Matrix user ID format: %s", matrixUserID), errContext)
	}
	
	parts := strings.SplitN(matrixUserID[1:], ":", 2) // Remove @ and split on first :
	if len(parts) != 2 {
		return nil, logAndReturnError("invalid_matrix_user_id", 
			fmt.Errorf("could not parse Matrix user ID: %s", matrixUserID), errContext)
	}
	
	localpart := parts[0]
	serverName := parts[1]
	
	slog.Info("Attempting Matrix account reactivation by creating new account variant", 
		"original_matrix_user_id", matrixUserID,
		"original_localpart", localpart,
		"server_name", serverName)
	
	// Since Dendrite doesn't support true reactivation of deactivated accounts,
	// we'll create a new account with a suffix and store the original user ID in the database
	// The user will see the original user ID but internally we use the new one
	
	// Try creating accounts with incremental suffixes until we find one that works
	for attempt := 1; attempt <= 10; attempt++ {
		var newLocalpart string
		if attempt == 1 {
			// First try with "_reactivated" suffix
			newLocalpart = localpart + "_reactivated"
		} else {
			// Then try with numbered suffixes
			newLocalpart = fmt.Sprintf("%s_reactivated_%d", localpart, attempt-1)
		}
		
		slog.Info("Attempting reactivation with new localpart", 
			"attempt", attempt,
			"new_localpart", newLocalpart,
			"original_matrix_user_id", matrixUserID)
		
		registrationResponse, err := RegisterUserWithSharedSecret(newLocalpart, newPassword, false)
		if err != nil {
			if strings.Contains(err.Error(), "M_USER_IN_USE") {
				slog.Info("Localpart still in use, trying next variant", 
					"attempted_localpart", newLocalpart,
					"attempt", attempt)
				continue // Try next suffix
			}
			
			// Non-conflict error, fail immediately
			return nil, logAndReturnError("reactivation_registration_failed", fmt.Errorf(
				"failed to register new Matrix account for reactivation: %w", err), errContext)
		}
		
		// Success! We created a new Matrix account
		slog.Info("Successfully created new Matrix account for reactivation", 
			"original_matrix_user_id", matrixUserID,
			"new_matrix_user_id", registrationResponse.UserID,
			"attempt", attempt)
		
		// Return the response but we'll store the original user ID in the database for UI consistency
		return registrationResponse, nil
	}
	
	// If we get here, we tried 10 different suffixes and they were all taken
	return nil, logAndReturnError("reactivation_all_variants_taken", 
		errors.New("could not find available Matrix user ID variant for reactivation after 10 attempts"), errContext)
}


