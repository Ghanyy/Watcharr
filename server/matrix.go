// ExportMatrixCredentials exports Matrix credentials for auto-generated users
func ExportMatrixCredentials(db *gorm.DB, watcharrUserID uint, deletePasswordAfterExport bool) (*MatrixCredentialExport, error) {
	errContext := map[string]interface{}{
		"watcharr_user_id": watcharrUserID,
	}

	// Get the Matrix user
	var matrixUser MatrixUser
	if err := db.Where("user_id = ?", watcharrUserID).First(&matrixUser).Error; err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return nil, fmt.Errorf("no Matrix account linked for this user")
		}
		return nil, logAndReturnError("database_find", err, errContext)
	}

	errContext["matrix_user_id"] = matrixUser.MatrixUserID
	errContext["is_auto_generated"] = matrixUser.IsAutoGenerated

	// Security check: Only allow export for auto-generated accounts
	if !matrixUser.IsAutoGenerated {
		return nil, logAndReturnError("credential_export_denied", 
			errors.New("credential export is only available for auto-generated Matrix accounts"), 
			errContext)
	}

	// Security check: Ensure password is available
	if matrixUser.EncryptedPassword == "" {
		return nil, logAndReturnError("no_password_available", 
			errors.New("no password available for export - account may be a placeholder"), 
			errContext)
	}

	// Rate limiting: Check export count (max 10 exports total, max 3 per hour)
	if matrixUser.PasswordExportCount >= 10 {
		return nil, logAndReturnError("export_limit_exceeded", 
			errors.New("maximum number of password exports exceeded for security"), 
			errContext)
	}

	// Check if exported recently (within last 5 minutes)
	if matrixUser.PasswordExportedAt != nil {
		fiveMinutesAgo := time.Now().Add(-5 * time.Minute)
		if matrixUser.PasswordExportedAt.After(fiveMinutesAgo) {
			// Limit to one export per 5 minutes
			return nil, logAndReturnError("export_rate_limited", 
				fmt.Errorf("password was exported recently at %s - please wait at least 5 minutes between exports", 
					matrixUser.PasswordExportedAt.Format("2006-01-02 15:04:05")), 
				errContext)
		}
	}

	// Decrypt the password
	password, err := decryptToken(matrixUser.EncryptedPassword)
	if err != nil {
		// If decryption fails, it's likely due to encryption key change after server restart
		// Provide a helpful error message
		return nil, logAndReturnError("password_decryption", 
			fmt.Errorf("failed to decrypt password - this may be due to server restart. Please recreate your Matrix account: %w", err), 
			errContext)
	}

	// Create export response
	export := &MatrixCredentialExport{
		MatrixUserID: matrixUser.MatrixUserID,
		Password:     password,
		ServerURL:    Config.MOVIE_CLUB.Matrix.ServerURL,
		ServerName:   Config.MOVIE_CLUB.Matrix.ServerName,
		ExportedAt:   time.Now(),
	}

	// Update export tracking
	now := time.Now()
	matrixUser.PasswordExported = true
	matrixUser.PasswordExportedAt = &now
	matrixUser.PasswordExportCount++

	// Optionally delete password after export for enhanced security
	if deletePasswordAfterExport {
		matrixUser.EncryptedPassword = ""
		slog.Info("Password deleted after export for enhanced security", 
			"watcharr_user_id", watcharrUserID,
			"matrix_user_id", matrixUser.MatrixUserID)
	}

	// Save changes
	if err := db.Save(&matrixUser).Error; err != nil {
		return nil, logAndReturnError("export_tracking_update", err, errContext)
	}

	slog.Info("Matrix credentials exported", 
		"watcharr_user_id", watcharrUserID,
		"matrix_user_id", matrixUser.MatrixUserID,
		"export_count", matrixUser.PasswordExportCount,
		"password_deleted", deletePasswordAfterExport)

	return export, nil
}

