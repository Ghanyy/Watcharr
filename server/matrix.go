// LinkCustomMatrixUser validates and links a custom Matrix user
func LinkCustomMatrixUser(db *gorm.DB, watcharrUserID uint, matrixUserID string, accessToken string) error {
	errContext := map[string]interface{}{
		"watcharr_user_id": watcharrUserID,
		"matrix_user_id": matrixUserID,
	}

	// Validate Matrix user ID format
	if err := validateMatrixUserID(matrixUserID); err != nil {
		return logAndReturnError("user_id_validation", err, errContext)
	}

	// Validate access token format
	if err := validateAccessToken(accessToken); err != nil {
		return logAndReturnError("access_token_validation", err, errContext)
	}

	// Validate Matrix user exists and token works
	if err := ValidateMatrixUser(matrixUserID, accessToken); err != nil {
		return logAndReturnError("user_validation", err, errContext)
	}

	// Check for existing Matrix users for this Watcharr user
	var existingUsers []MatrixUser
	if err := db.Where("user_id = ?", watcharrUserID).Find(&existingUsers).Error; err != nil {
		slog.Warn("Failed to check existing Matrix users", 
			"watcharr_user_id", watcharrUserID, 
			"error", err)
	} else {
		slog.Info("Found existing Matrix users before linking", 
			"watcharr_user_id", watcharrUserID, 
			"count", len(existingUsers))
		for i, user := range existingUsers {
			slog.Info("Existing Matrix user", 
				"index", i,
				"matrix_user_id", user.MatrixUserID,
				"is_auto_generated", user.IsAutoGenerated)
		}
	}

	// Get user's current Matrix rooms before removing auto-generated account
	var previousRooms []MatrixRoom
	if len(existingUsers) > 0 {
		rooms, err := GetUserCurrentMatrixRooms(db, watcharrUserID)
		if err != nil {
			slog.Warn("Failed to get user's current rooms for transfer", 
				"watcharr_user_id", watcharrUserID, 
				"error", err)
		} else {
			previousRooms = rooms
			slog.Info("Found rooms for account transfer", 
				"watcharr_user_id", watcharrUserID, 
				"room_count", len(previousRooms))
		}
	}

	// Remove auto-generated user if exists
	if err := RemoveAutoGeneratedUser(db, watcharrUserID); err != nil {
		slog.Warn("Failed to remove auto-generated user", 
			"watcharr_user_id", watcharrUserID, 
			"error", err)
	}

	// Encrypt the access token before storing
	encryptedToken, err := encryptToken(accessToken)
	if err != nil {
		return logAndReturnError("token_encryption", err, errContext)
	}

	// Store custom user mapping
	matrixUser := &MatrixUser{
		UserID:          watcharrUserID,
		MatrixUserID:    matrixUserID,
		IsAutoGenerated: false,
		AccessToken:     encryptedToken,
	}

	slog.Info("Creating Matrix user record", 
		"watcharr_user_id", watcharrUserID,
		"matrix_user_id", matrixUserID,
		"is_auto_generated", matrixUser.IsAutoGenerated)

	// Create the record and then explicitly update the IsAutoGenerated field
	// This works around GORM default value behavior
	if err := db.Create(matrixUser).Error; err != nil {
		return logAndReturnError("database_create", err, errContext)
	}

	// Explicitly update the IsAutoGenerated field to ensure it's set correctly
	if err := db.Model(matrixUser).Update("is_auto_generated", false).Error; err != nil {
		slog.Warn("Failed to update is_auto_generated flag", 
			"watcharr_user_id", watcharrUserID,
			"error", err)
	}

	// Verify what was actually created
	var createdUser MatrixUser
	if err := db.Where("user_id = ? AND matrix_user_id = ?", watcharrUserID, matrixUserID).First(&createdUser).Error; err != nil {
		slog.Warn("Failed to verify created Matrix user", "error", err)
	} else {
		slog.Info("Verified created Matrix user", 
			"watcharr_user_id", createdUser.UserID,
			"matrix_user_id", createdUser.MatrixUserID,
			"is_auto_generated", createdUser.IsAutoGenerated)
	}

	// Invite the new custom account to previously accessible rooms
	if len(previousRooms) > 0 {
		slog.Info("Inviting custom Matrix account to previous rooms", 
			"watcharr_user_id", watcharrUserID,
			"matrix_user_id", matrixUserID,
			"room_count", len(previousRooms))
		
		if err := InviteUserToExistingRooms(db, matrixUserID, watcharrUserID, previousRooms); err != nil {
			slog.Warn("Failed to invite custom Matrix user to some previous rooms", 
				"watcharr_user_id", watcharrUserID,
				"matrix_user_id", matrixUserID,
				"error", err,
				"note", "User may need to be manually invited to some rooms")
		}
	}

	slog.Info("Linked custom Matrix user", "watcharr_user_id", watcharrUserID, "matrix_user_id", matrixUserID)
	return nil
}

// UnlinkMatrixUser removes a user's Matrix account link
// UnlinkMatrixUserV2 handles unlinking for both legacy and new account types
func UnlinkMatrixUserV2(db *gorm.DB, watcharrUserID uint) error {
	errContext := map[string]interface{}{
		"watcharr_user_id": watcharrUserID,
	}

	// Check for new account type first
	var matrixUserV2 MatrixUserV2
	if err := db.Where("user_id = ?", watcharrUserID).First(&matrixUserV2).Error; err == nil {
		// Handle new account type
		return unlinkMatrixUserV2(db, &matrixUserV2, watcharrUserID, errContext)
	}

	// Check for legacy account
	var matrixUser MatrixUser
	if err := db.Where("user_id = ?", watcharrUserID).First(&matrixUser).Error; err == nil {
		// Handle legacy account
		return unlinkLegacyMatrixUser(db, &matrixUser, watcharrUserID, errContext)
	}

	return fmt.Errorf("no Matrix account linked for this user")
}

// unlinkMatrixUserV2 handles unlinking for new MatrixUserV2 accounts
func unlinkMatrixUserV2(db *gorm.DB, matrixUser *MatrixUserV2, watcharrUserID uint, errContext map[string]interface{}) error {
	errContext["matrix_user_id"] = matrixUser.MatrixUserID
	errContext["account_type"] = matrixUser.AccountType
	errContext["is_auto_generated"] = matrixUser.IsAutoGenerated
	errContext["as_managed_user"] = matrixUser.ASManagedUser

	if matrixUser.AccountType == AccountTypeAppService {
		// For AS users, use the Application Service manager to delete them
		if appServiceManager != nil {
			slog.Info("Deleting Application Service user",
				"watcharr_user_id", watcharrUserID,
				"matrix_user_id", matrixUser.MatrixUserID)
			
			if err := appServiceManager.DeleteUser(watcharrUserID); err != nil {
				return logAndReturnError("as_user_deletion", err, errContext)
			}
		} else {
			// If AS manager not available, just remove from database
			slog.Warn("Application Service manager not available, removing user from database only",
				"watcharr_user_id", watcharrUserID,
				"matrix_user_id", matrixUser.MatrixUserID)
			
			if err := db.Delete(matrixUser).Error; err != nil {
				return logAndReturnError("database_delete", err, errContext)
			}
		}
	} else if matrixUser.AccountType == AccountTypePersonal {
		// For personal accounts, use similar logic to legacy accounts
		if matrixUser.IsAutoGenerated {
			// Auto-generated personal accounts: deactivate on server
			slog.Info("Removing auto-generated personal Matrix user from rooms and deactivating",
				"watcharr_user_id", watcharrUserID,
				"matrix_user_id", matrixUser.MatrixUserID)
			
			if err := RemoveUserFromMatrixRooms(db, matrixUser.MatrixUserID, watcharrUserID); err != nil {
				slog.Warn("Failed to remove Matrix user from some rooms", "error", err)
			}
			
			if err := DeactivateMatrixUser(db, matrixUser.MatrixUserID); err != nil {
				slog.Warn("Failed to deactivate Matrix user on server", "error", err)
			}
			
			// Soft delete the account for potential reactivation
			if err := db.Delete(matrixUser).Error; err != nil {
				return logAndReturnError("database_delete", err, errContext)
			}
		} else {
			// Custom personal accounts: preserve on server
			slog.Info("Unlinking custom personal Matrix account - preserving user on Matrix server",
				"watcharr_user_id", watcharrUserID,
				"matrix_user_id", matrixUser.MatrixUserID)
			
			if err := db.Delete(matrixUser).Error; err != nil {
				return logAndReturnError("database_delete", err, errContext)
			}
		}
	}

	slog.Info("Successfully unlinked Matrix user",
		"watcharr_user_id", watcharrUserID,
		"matrix_user_id", matrixUser.MatrixUserID,
		"account_type", matrixUser.AccountType)

	return nil
}

// unlinkLegacyMatrixUser handles unlinking for legacy MatrixUser accounts
func unlinkLegacyMatrixUser(db *gorm.DB, matrixUser *MatrixUser, watcharrUserID uint, errContext map[string]interface{}) error {
	errContext["matrix_user_id"] = matrixUser.MatrixUserID
	errContext["is_auto_generated"] = matrixUser.IsAutoGenerated

	// Handle different unlinking behavior based on account type
	if matrixUser.IsAutoGenerated {
		// For auto-generated accounts, remove from rooms and deactivate the user on Matrix server
		slog.Info("Removing auto-generated Matrix user from all rooms before deactivation",
			"watcharr_user_id", watcharrUserID,
			"matrix_user_id", matrixUser.MatrixUserID)
		
		if err := RemoveUserFromMatrixRooms(db, matrixUser.MatrixUserID, watcharrUserID); err != nil {
			slog.Warn("Failed to remove Matrix user from some rooms",
				"watcharr_user_id", watcharrUserID,
				"matrix_user_id", matrixUser.MatrixUserID,
				"error", err,
				"note", "User may remain in some rooms on Matrix server")
		}
		
		slog.Info("Attempting to deactivate auto-generated Matrix user on server",
			"watcharr_user_id", watcharrUserID,
			"matrix_user_id", matrixUser.MatrixUserID)
		
		if err := DeactivateMatrixUser(db, matrixUser.MatrixUserID); err != nil {
			// Log the error but don't fail the unlinking process
			slog.Warn("Failed to deactivate Matrix user on server",
				"watcharr_user_id", watcharrUserID,
				"matrix_user_id", matrixUser.MatrixUserID,
				"error", err,
				"note", "User will be removed from Watcharr database but may remain active on Matrix server")
		}
		
		// Soft delete the account for potential reactivation
		if err := db.Delete(matrixUser).Error; err != nil {
			return logAndReturnError("database_delete", err, errContext)
		}
	} else {
		// For custom accounts, we only remove from Watcharr - preserve the Matrix account
		// The user can manually leave rooms if they wish
		slog.Info("Unlinking custom Matrix account - preserving user on Matrix server",
			"watcharr_user_id", watcharrUserID,
			"matrix_user_id", matrixUser.MatrixUserID)
		
		if err := db.Delete(matrixUser).Error; err != nil {
			return logAndReturnError("database_delete", err, errContext)
		}
	}

	slog.Info("Successfully unlinked legacy Matrix user",
		"watcharr_user_id", watcharrUserID,
		"matrix_user_id", matrixUser.MatrixUserID)

	return nil
}

