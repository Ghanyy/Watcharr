// Shared secret registration functions

// generateNonce creates a unique nonce for shared secret registration
func generateNonce() (string, error) {
	// Generate timestamp + random hex for uniqueness
	// Use UTC to avoid timezone mismatch issues with Dendrite server
	timestamp := time.Now().UTC().Unix()
	randomBytes := make([]byte, 8)
	if _, err := rand.Read(randomBytes); err != nil {
		return "", fmt.Errorf("failed to generate random bytes: %w", err)
	}
	randomHex := hex.EncodeToString(randomBytes)
	return fmt.Sprintf("%d_%s", timestamp, randomHex), nil
}

// generateSharedSecretMAC creates HMAC-SHA1 signature for shared secret registration
func generateSharedSecretMAC(sharedSecret, nonce, username, password string, admin bool) (string, error) {
	if sharedSecret == "" {
		return "", errors.New("shared secret is empty")
	}
	
	// Determine admin flag
	adminFlag := "notadmin"
	if admin {
		adminFlag = "admin"
	}
	
	// Create message: nonce + \0 + username + \0 + password + \0 + admin_flag
	// Build message with actual null byte separators (not literal \x00 strings)
	var message bytes.Buffer
	message.WriteString(nonce)
	message.WriteByte(0)
	message.WriteString(username)
	message.WriteByte(0)
	message.WriteString(password)
	message.WriteByte(0)
	message.WriteString(adminFlag)
	
	// Generate HMAC-SHA1
	mac := hmac.New(sha1.New, []byte(sharedSecret))
	mac.Write(message.Bytes())
	
	return hex.EncodeToString(mac.Sum(nil)), nil
}

// getServerNonce fetches a nonce from the Matrix server for shared secret registration
func getServerNonce() (string, error) {
	// Make GET request to fetch nonce
	url := fmt.Sprintf("%s/_synapse/admin/v1/register", Config.MOVIE_CLUB.Matrix.ServerURL)
	resp, err := http.Get(url)
	if err != nil {
		return "", fmt.Errorf("failed to fetch nonce: %w", err)
	}
	defer resp.Body.Close()
	
	// Check status code
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("nonce request failed with status %d", resp.StatusCode)
	}
	
	// Read and parse response
	var nonceResponse SharedSecretNonceResponse
	if err := json.NewDecoder(resp.Body).Decode(&nonceResponse); err != nil {
		return "", fmt.Errorf("failed to parse nonce response: %w", err)
	}
	
	if nonceResponse.Nonce == "" {
		return "", errors.New("server returned empty nonce")
	}
	
	slog.Debug("Fetched nonce from Matrix server", "nonce", nonceResponse.Nonce)
	return nonceResponse.Nonce, nil
}

// RegisterUserWithSharedSecret creates a Matrix user using shared secret registration
func RegisterUserWithSharedSecret(username, password string, admin bool) (*SharedSecretRegistrationResponse, error) {
	errContext := map[string]interface{}{
		"username": username,
		"admin":    admin,
	}
	
	// Check if shared secret is configured
	if Config.MOVIE_CLUB.Matrix.RegistrationSecret == "" {
		return nil, logAndReturnError("shared_secret_registration", 
			errors.New("shared secret not configured"), errContext)
	}
	
	// Get nonce from server (Dendrite requires server-generated nonce)
	nonce, err := getServerNonce()
	if err != nil {
		return nil, logAndReturnError("nonce_fetch", err, errContext)
	}
	errContext["nonce"] = nonce
	
	// Generate HMAC signature
	mac, err := generateSharedSecretMAC(Config.MOVIE_CLUB.Matrix.RegistrationSecret, nonce, username, password, admin)
	if err != nil {
		return nil, logAndReturnError("mac_generation", err, errContext)
	}
	
	// Prepare request
	request := SharedSecretRegistrationRequest{
		Nonce:    nonce,
		Username: username,
		Password: password,
		Admin:    admin,
		Mac:      mac,
	}
	
	// Convert to JSON
	requestJSON, err := json.Marshal(request)
	if err != nil {
		return nil, logAndReturnError("json_marshal", err, errContext)
	}
	
	// Make HTTP request to Matrix server
	url := fmt.Sprintf("%s/_synapse/admin/v1/register", Config.MOVIE_CLUB.Matrix.ServerURL)
	resp, err := http.Post(url, "application/json", bytes.NewBuffer(requestJSON))
	if err != nil {
		return nil, logAndReturnError("http_request", err, errContext)
	}
	defer resp.Body.Close()
	
	// Read response
	var responseBody bytes.Buffer
	if _, err := responseBody.ReadFrom(resp.Body); err != nil {
		return nil, logAndReturnError("response_read", err, errContext)
	}
	
	// Check status code
	if resp.StatusCode != http.StatusOK {
		return nil, logAndReturnError("registration_failed", 
			fmt.Errorf("registration failed with status %d: %s", resp.StatusCode, responseBody.String()), 
			errContext)
	}
	
	// Parse response
	var registrationResponse SharedSecretRegistrationResponse
	if err := json.Unmarshal(responseBody.Bytes(), &registrationResponse); err != nil {
		return nil, logAndReturnError("response_parse", err, errContext)
	}
	
	slog.Info("Successfully registered Matrix user via shared secret",
		"username", username,
		"user_id", registrationResponse.UserID,
		"device_id", registrationResponse.DeviceID)
	
	return &registrationResponse, nil
}

// ExportMatrixCredentials exports Matrix credentials for auto-generated users
func ExportMatrixCredentials(db *gorm.DB, watcharrUserID uint, deletePasswordAfterExport bool) (*MatrixCredentialExport, error) {
	errContext := map[string]interface{}{
		"watcharr_user_id": watcharrUserID,
	}

	// Get the Matrix user
	var matrixUser MatrixUser
	if err := db.Where("user_id = ?", watcharrUserID).First(&matrixUser).Error; err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return nil, fmt.Errorf("no Matrix account linked for this user")
		}
		return nil, logAndReturnError("database_find", err, errContext)
	}

	errContext["matrix_user_id"] = matrixUser.MatrixUserID
	errContext["is_auto_generated"] = matrixUser.IsAutoGenerated

	// Security check: Only allow export for auto-generated accounts
	if !matrixUser.IsAutoGenerated {
		return nil, logAndReturnError("credential_export_denied", 
			errors.New("credential export is only available for auto-generated Matrix accounts"), 
			errContext)
	}

	// Security check: Ensure password is available
	if matrixUser.EncryptedPassword == "" {
		return nil, logAndReturnError("no_password_available", 
			errors.New("no password available for export - account may be a placeholder"), 
			errContext)
	}

	// Rate limiting: Check export count (max 10 exports total, max 3 per hour)
	if matrixUser.PasswordExportCount >= 10 {
		return nil, logAndReturnError("export_limit_exceeded", 
			errors.New("maximum number of password exports exceeded for security"), 
			errContext)
	}

	// Check if exported recently (within last hour)
	if matrixUser.PasswordExportedAt != nil {
		hourAgo := time.Now().Add(-1 * time.Hour)
		if matrixUser.PasswordExportedAt.After(hourAgo) {
			// Count recent exports by checking if exported 3+ times in last hour
			// For simplicity, we'll just limit to one export per hour
			return nil, logAndReturnError("export_rate_limited", 
				fmt.Errorf("password was exported recently at %s - please wait at least 1 hour between exports", 
					matrixUser.PasswordExportedAt.Format("2006-01-02 15:04:05")), 
				errContext)
		}
	}

	// Decrypt the password
	password, err := decryptToken(matrixUser.EncryptedPassword)
	if err != nil {
		return nil, logAndReturnError("password_decryption", err, errContext)
	}

	// Create export response
	export := &MatrixCredentialExport{
		MatrixUserID: matrixUser.MatrixUserID,
		Password:     password,
		ServerURL:    Config.MOVIE_CLUB.Matrix.ServerURL,
		ServerName:   Config.MOVIE_CLUB.Matrix.ServerName,
		ExportedAt:   time.Now(),
	}

	// Update export tracking
	now := time.Now()
	matrixUser.PasswordExported = true
	matrixUser.PasswordExportedAt = &now
	matrixUser.PasswordExportCount++

	// Optionally delete password after export for enhanced security
	if deletePasswordAfterExport {
		matrixUser.EncryptedPassword = ""
		slog.Info("Password deleted after export for enhanced security", 
			"watcharr_user_id", watcharrUserID,
			"matrix_user_id", matrixUser.MatrixUserID)
	}

	// Save changes
	if err := db.Save(&matrixUser).Error; err != nil {
		return nil, logAndReturnError("export_tracking_update", err, errContext)
	}

	slog.Info("Matrix credentials exported", 
		"watcharr_user_id", watcharrUserID,
		"matrix_user_id", matrixUser.MatrixUserID,
		"export_count", matrixUser.PasswordExportCount,
		"password_deleted", deletePasswordAfterExport)

	return export, nil
}

// MatrixCredentialExport represents exported Matrix credentials
type MatrixCredentialExport struct {
	MatrixUserID string    `json:"matrixUserId"`
	Password     string    `json:"password"`
	ServerURL    string    `json:"serverUrl"`
	ServerName   string    `json:"serverName"`
	ExportedAt   time.Time `json:"exportedAt"`
}

// DeactivateMatrixUser deactivates a Matrix user via admin API (if supported)
func DeactivateMatrixUser(matrixUserID string) error {
	errContext := map[string]interface{}{
		"matrix_user_id": matrixUserID,
	}
	
	// Check if admin token is configured
	if Config.MOVIE_CLUB.Matrix.AdminToken == "" {
		return logAndReturnError("user_deactivation", 
			errors.New("admin token not configured"), errContext)
	}
	
	// For Dendrite, user deactivation might not be supported via admin API
	// This is a best-effort attempt that may need to be updated based on Dendrite version
	
	// Try Synapse-compatible deactivation endpoint first
	url := fmt.Sprintf("%s/_synapse/admin/v1/deactivate/%s", Config.MOVIE_CLUB.Matrix.ServerURL, matrixUserID)
	
	requestBody := map[string]interface{}{
		"erase": true, // Remove user data completely
	}
	
	requestJSON, err := json.Marshal(requestBody)
	if err != nil {
		return logAndReturnError("json_marshal", err, errContext)
	}
	
	// Create HTTP request
	req, err := http.NewRequest("POST", url, bytes.NewBuffer(requestJSON))
	if err != nil {
		return logAndReturnError("request_creation", err, errContext)
	}
	
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", fmt.Sprintf("Bearer %s", Config.MOVIE_CLUB.Matrix.AdminToken))
	
	// Make request
	client := &http.Client{Timeout: 30 * time.Second}
	resp, err := client.Do(req)
	if err != nil {
		return logAndReturnError("http_request", err, errContext)
	}
	defer resp.Body.Close()
	
	// Read response
	var responseBody bytes.Buffer
	if _, err := responseBody.ReadFrom(resp.Body); err != nil {
		return logAndReturnError("response_read", err, errContext)
	}
	
	// Check response
	if resp.StatusCode == http.StatusOK {
		slog.Info("Successfully deactivated Matrix user", "matrix_user_id", matrixUserID)
		return nil
	} else if resp.StatusCode == http.StatusNotFound {
		// Endpoint not supported by this Matrix server
		slog.Warn("Matrix server does not support user deactivation API", 
			"matrix_user_id", matrixUserID,
			"status_code", resp.StatusCode,
			"note", "Manual user deactivation may be required")
		return nil // Don't treat this as an error
	} else {
		return logAndReturnError("deactivation_failed", 
			fmt.Errorf("deactivation failed with status %d: %s", resp.StatusCode, responseBody.String()), 
			errContext)
	}
}

