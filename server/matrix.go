// Migration functions for existing Matrix users

// MigrateMatrixUsersToV2 migrates all legacy MatrixUser accounts to MatrixUserV2
func MigrateMatrixUsersToV2(db *gorm.DB) (*MatrixMigrationResult, error) {
	result := &MatrixMigrationResult{
		TotalLegacyUsers:    0,
		MigratedUsers:       0,
		FailedMigrations:    0,
		SkippedUsers:        0,
		MigratedUserIDs:     make([]uint, 0),
		Errors:              make([]string, 0),
	}

	// Get all legacy Matrix users
	var legacyUsers []MatrixUser
	if err := db.Find(&legacyUsers).Error; err != nil {
		return result, fmt.Errorf("failed to fetch legacy Matrix users: %w", err)
	}

	result.TotalLegacyUsers = len(legacyUsers)
	
	if len(legacyUsers) == 0 {
		slog.Info("No legacy Matrix users found for migration")
		return result, nil
	}

	slog.Info("Starting Matrix user migration", "total_users", len(legacyUsers))

	for _, legacyUser := range legacyUsers {
		// Check if user already has a V2 account
		var existingV2User MatrixUserV2
		if err := db.Where("user_id = ?", legacyUser.UserID).First(&existingV2User).Error; err == nil {
			slog.Info("User already has V2 account, skipping migration",
				"watcharr_user_id", legacyUser.UserID,
				"legacy_matrix_user_id", legacyUser.MatrixUserID,
				"v2_matrix_user_id", existingV2User.MatrixUserID)
			result.SkippedUsers++
			continue
		}

		// Migrate the user
		if err := migrateSingleUserToV2(db, &legacyUser); err != nil {
			errorMsg := fmt.Sprintf("Failed to migrate user %d (%s): %v", 
				legacyUser.UserID, legacyUser.MatrixUserID, err)
			slog.Error("Matrix user migration failed",
				"watcharr_user_id", legacyUser.UserID,
				"matrix_user_id", legacyUser.MatrixUserID,
				"error", err)
			
			result.FailedMigrations++
			result.Errors = append(result.Errors, errorMsg)
			continue
		}

		result.MigratedUsers++
		result.MigratedUserIDs = append(result.MigratedUserIDs, legacyUser.UserID)
		
		slog.Info("Successfully migrated Matrix user",
			"watcharr_user_id", legacyUser.UserID,
			"matrix_user_id", legacyUser.MatrixUserID)
	}

	slog.Info("Matrix user migration completed",
		"total_users", result.TotalLegacyUsers,
		"migrated", result.MigratedUsers,
		"skipped", result.SkippedUsers,
		"failed", result.FailedMigrations)

	return result, nil
}

// migrateSingleUserToV2 migrates a single legacy MatrixUser to MatrixUserV2
func migrateSingleUserToV2(db *gorm.DB, legacyUser *MatrixUser) error {
	// Create new V2 user with legacy data
	v2User := &MatrixUserV2{
		UserID:              legacyUser.UserID,
		MatrixUserID:        legacyUser.MatrixUserID,
		AccountType:         AccountTypePersonal, // Legacy accounts are personal accounts
		IsAutoGenerated:     legacyUser.IsAutoGenerated,
		AccessToken:         legacyUser.AccessToken,
		DeviceID:            legacyUser.DeviceID,
		EncryptedPassword:   legacyUser.EncryptedPassword,
		PasswordExported:    legacyUser.PasswordExported,
		PasswordExportedAt:  legacyUser.PasswordExportedAt,
		PasswordExportCount: legacyUser.PasswordExportCount,
		ASManagedUser:       false, // Legacy accounts are not AS managed
		CreatedViaAS:        false, // Legacy accounts were not created via AS
		LastSeenAt:          time.Now(), // Set current time as last seen
	}

	// Start transaction for atomic migration
	return db.Transaction(func(tx *gorm.DB) error {
		// Create the V2 user
		if err := tx.Create(v2User).Error; err != nil {
			return fmt.Errorf("failed to create V2 user: %w", err)
		}

		// Mark legacy user as migrated (soft delete)
		if err := tx.Delete(legacyUser).Error; err != nil {
			return fmt.Errorf("failed to soft delete legacy user: %w", err)
		}

		return nil
	})
}

