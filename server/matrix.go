// Shared secret registration functions

// generateNonce creates a unique nonce for shared secret registration
func generateNonce() (string, error) {
	// Generate timestamp + random hex for uniqueness
	// Use UTC to avoid timezone mismatch issues with Dendrite server
	timestamp := time.Now().UTC().Unix()
	randomBytes := make([]byte, 8)
	if _, err := rand.Read(randomBytes); err != nil {
		return "", fmt.Errorf("failed to generate random bytes: %w", err)
	}
	randomHex := hex.EncodeToString(randomBytes)
	return fmt.Sprintf("%d_%s", timestamp, randomHex), nil
}

// generateSharedSecretMAC creates HMAC-SHA1 signature for shared secret registration
func generateSharedSecretMAC(sharedSecret, nonce, username, password string, admin bool) (string, error) {
	if sharedSecret == "" {
		return "", errors.New("shared secret is empty")
	}
	
	// Determine admin flag
	adminFlag := "notadmin"
	if admin {
		adminFlag = "admin"
	}
	
	// Create message: nonce + \0 + username + \0 + password + \0 + admin_flag
	// Build message with actual null byte separators (not literal \x00 strings)
	var message bytes.Buffer
	message.WriteString(nonce)
	message.WriteByte(0)
	message.WriteString(username)
	message.WriteByte(0)
	message.WriteString(password)
	message.WriteByte(0)
	message.WriteString(adminFlag)
	
	// Generate HMAC-SHA1
	mac := hmac.New(sha1.New, []byte(sharedSecret))
	mac.Write(message.Bytes())
	
	return hex.EncodeToString(mac.Sum(nil)), nil
}

