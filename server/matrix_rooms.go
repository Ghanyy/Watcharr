// Space Hierarchy Management

// AddRoomToSpace adds a room to a space (replaces AddRoomToMovieClubSpace for new structure)
func AddRoomToSpace(db *gorm.DB, room *MatrixRoom, space *MatrixSpace) error {
	if matrixClient == nil {
		return errors.New("matrix client not initialized")
	}

	// Update database relationship
	room.SpaceID = &space.SpaceID
	if err := db.Save(room).Error; err != nil {
		return fmt.Errorf("failed to update room space relationship: %w", err)
	}

	spaceID := id.RoomID(space.SpaceID)
	childRoomID := id.RoomID(room.RoomID)

	// Add room as child of space
	stateKey := room.RoomID
	content := map[string]interface{}{
		"via": []string{Config.MOVIE_CLUB.Matrix.ServerName},
	}
	_, err := matrixClient.SendStateEvent(context.Background(), spaceID, event.StateSpaceChild, stateKey, content)

	if err != nil {
		return fmt.Errorf("failed to add room to space: %w", err)
	}

	// Add space as parent of room
	parentContent := map[string]interface{}{
		"via": []string{Config.MOVIE_CLUB.Matrix.ServerName},
	}
	_, err = matrixClient.SendStateEvent(context.Background(), childRoomID, event.StateSpaceParent, space.SpaceID, parentContent)

	if err != nil {
		slog.Warn("Failed to set space as parent of room", "error", err)
		// Don't return error as the main relationship is established
	}

	slog.Debug("Added room to space", "room_id", room.RoomID, "space_id", space.SpaceID)
	return nil
}

