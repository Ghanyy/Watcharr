// createRoomInSpace creates a specific room type within a cycle space
func createRoomInSpace(db *gorm.DB, space *MatrixSpace, cycle *MovieClubCycle, roomType MatrixRoomType, roomName, roomTopic string) (*MatrixRoom, error) {
	if matrixClient == nil {
		return nil, errors.New("matrix client not initialized")
	}

	// Generate room alias
	var movieTitle string
	if cycle.WinnerContent != nil {
		movieTitle = cycle.WinnerContent.Title
	} else {
		movieTitle = fmt.Sprintf("cycle-%d", cycle.ID)
	}

	normalizedTitle := normalizeTitle(movieTitle)
	roomAlias := fmt.Sprintf("movieclub-%s-%s-%s", 
		cycle.VotingEndDate.Format("2006-01-02"), 
		normalizedTitle, 
		string(roomType))

	// Create room
	createReq := &mautrix.ReqCreateRoom{
		RoomAliasName: roomAlias,
		Name:          roomName,
		Topic:         roomTopic,
		Preset:        "private_chat",
		Visibility:    "private",
		IsDirect:      false,
	}

	resp, err := matrixClient.CreateRoom(context.Background(), createReq)
	if err != nil {
		return nil, fmt.Errorf("failed to create %s room: %w", roomType, err)
	}

	// Store room in database
	matrixRoom := &MatrixRoom{
		RoomID:    resp.RoomID.String(),
		RoomAlias: fmt.Sprintf("#%s:%s", roomAlias, Config.MOVIE_CLUB.Matrix.ServerName),
		RoomName:  roomName,
		RoomType:  roomType,
		SpaceID:   &space.SpaceID,
		CycleID:   &cycle.ID,
	}

	if err := db.Create(matrixRoom).Error; err != nil {
		return nil, fmt.Errorf("failed to store %s room: %w", roomType, err)
	}

	slog.Info("Created room in cycle space",
		"cycle_id", cycle.ID,
		"room_type", roomType,
		"room_id", resp.RoomID,
		"alias", matrixRoom.RoomAlias,
		"space_id", space.SpaceID)

	// Add room to space
	if err := AddRoomToSpace(db, matrixRoom, space); err != nil {
		slog.Warn("Failed to add room to cycle space", "error", err, "room_id", resp.RoomID)
	}

	return matrixRoom, nil
}

