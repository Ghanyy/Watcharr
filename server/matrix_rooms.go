// Cycle Space Creation

// CreateCycleSpace creates a space for a movie club cycle
func CreateCycleSpace(db *gorm.DB, cycle *MovieClubCycle) (*MatrixSpace, error) {
	if matrixClient == nil {
		return nil, errors.New("matrix client not initialized")
	}

	// Check if space already exists for this cycle
	var existingSpace MatrixSpace
	if err := db.Where("cycle_id = ? AND space_type = ?", cycle.ID, MatrixSpaceTypeCycle).First(&existingSpace).Error; err == nil {
		slog.Debug("Space already exists for cycle", "cycle_id", cycle.ID, "space_id", existingSpace.SpaceID)
		return &existingSpace, nil
	}

	// Generate space name
	var movieTitle string
	if cycle.WinnerContent != nil {
		movieTitle = cycle.WinnerContent.Title
	} else {
		movieTitle = fmt.Sprintf("Cycle %d", cycle.ID)
	}
	
	spaceName := fmt.Sprintf("Cycle: %s (%s)",
		movieTitle,
		cycle.VotingEndDate.Format("2006-01-02"))

	// Create space
	createReq := &mautrix.ReqCreateRoom{
		Name:       spaceName,
		Topic:      fmt.Sprintf("Movie Club cycle space for %s", movieTitle),
		Preset:     "private_chat",
		Visibility: "private",
		CreationContent: map[string]interface{}{
			"type": "m.space",
		},
	}

	resp, err := matrixClient.CreateRoom(context.Background(), createReq)
	if err != nil {
		return nil, fmt.Errorf("failed to create cycle space: %w", err)
	}

	// Store space in database
	cycleSpace := &MatrixSpace{
		SpaceID:       resp.RoomID.String(),
		SpaceName:     spaceName,
		SpaceType:     MatrixSpaceTypeCycle,
		CycleID:       &cycle.ID,
		ParentSpaceID: nil, // Will be set when added to Movie Club space
	}

	if err := db.Create(cycleSpace).Error; err != nil {
		return nil, fmt.Errorf("failed to store cycle space: %w", err)
	}

	slog.Info("Created cycle space",
		"cycle_id", cycle.ID,
		"space_id", resp.RoomID,
		"space_name", spaceName,
		"movie", movieTitle)

	return cycleSpace, nil
}

