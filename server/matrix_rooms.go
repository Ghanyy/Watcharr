// EnsureNewsRoom creates or gets the global News room for all users
func EnsureNewsRoom(db *gorm.DB) (*MatrixRoom, error) {
	if matrixClient == nil {
		return nil, errors.New("matrix client not initialized")
	}

	// Check if News room already exists
	var existingRoom MatrixRoom
	if err := db.Where("room_type = ?", MatrixRoomTypeNews).First(&existingRoom).Error; err == nil {
		return &existingRoom, nil
	}

	// Ensure Movie Club space exists
	movieClubSpace, err := EnsureMovieClubSpace(db)
	if err != nil {
		return nil, fmt.Errorf("failed to ensure Movie Club space: %w", err)
	}

	// Create News room
	roomName := "News"
	createReq := &mautrix.ReqCreateRoom{
		Name:          roomName,
		Topic:         "Movie Club news and announcements",
		Preset:        "private_chat",
		Visibility:    "private",
		IsDirect:      false,
		RoomAliasName: "movieclub-news",
	}

	resp, err := matrixClient.CreateRoom(context.Background(), createReq)
	if err != nil {
		return nil, fmt.Errorf("failed to create News room: %w", err)
	}

	// Store room in database
	newsRoom := &MatrixRoom{
		RoomID:    resp.RoomID.String(),
		RoomAlias: fmt.Sprintf("#movieclub-news:%s", Config.MOVIE_CLUB.Matrix.ServerName),
		RoomName:  roomName,
		RoomType:  MatrixRoomTypeNews,
		SpaceID:   &movieClubSpace.SpaceID,
		CycleID:   nil, // News room is not associated with any cycle
	}

	if err := db.Create(newsRoom).Error; err != nil {
		return nil, fmt.Errorf("failed to store News room: %w", err)
	}

	slog.Info("Created News room",
		"room_id", resp.RoomID,
		"alias", newsRoom.RoomAlias)

	// Add room to Movie Club space
	if err := AddRoomToSpace(db, newsRoom, movieClubSpace); err != nil {
		slog.Warn("Failed to add News room to Movie Club space", "error", err)
	}

	// Invite all existing Matrix users to News room
	if err := InviteAllUsersToNewsRoom(db, newsRoom); err != nil {
		slog.Warn("Failed to invite all users to News room", "error", err)
	}

	return newsRoom, nil
}

