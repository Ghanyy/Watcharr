// RemoveUserFromMatrixRooms removes a Matrix user from all their rooms
func RemoveUserFromMatrixRooms(db *gorm.DB, matrixUserID string, watcharrUserID uint) error {
	if matrixClient == nil {
		return errors.New("matrix client not initialized")
	}

	// Get user's current rooms
	rooms, err := GetUserCurrentMatrixRooms(db, watcharrUserID)
	if err != nil {
		return fmt.Errorf("failed to get user's rooms for cleanup: %w", err)
	}

	if len(rooms) == 0 {
		slog.Info("No rooms to remove user from", "matrix_user_id", matrixUserID)
		return nil
	}

	successCount := 0
	errorCount := 0

	for _, room := range rooms {
		roomID := id.RoomID(room.RoomID)

		// Kick/ban the user from the room (remove them)
		_, err := matrixClient.KickUser(context.Background(), roomID, &mautrix.ReqKickUser{
			UserID: id.UserID(matrixUserID),
			Reason: "Account being unlinked from Watcharr",
		})

		if err != nil {
			slog.Warn("Failed to remove Matrix user from room",
				"matrix_user_id", matrixUserID,
				"room_id", roomID,
				"room_alias", room.RoomAlias,
				"error", err)
			errorCount++
			continue
		}

		successCount++
		slog.Debug("Removed Matrix user from room",
			"matrix_user_id", matrixUserID,
			"room_id", roomID,
			"room_alias", room.RoomAlias)
	}

	slog.Info("Matrix user removal from rooms complete",
		"matrix_user_id", matrixUserID,
		"watcharr_user_id", watcharrUserID,
		"removed_from", successCount,
		"errors", errorCount,
		"total_rooms", len(rooms))

	return nil
}

// Retroactive room creation functions

// GetActiveWatchingCyclesWithoutRooms returns cycles in watching phase that don't have Matrix rooms
func GetActiveWatchingCyclesWithoutRooms(db *gorm.DB) ([]MovieClubCycle, error) {
	var cycles []MovieClubCycle
	now := time.Now()

	// Find cycles that are:
	// 1. In watching phase (phase = 'watching' AND phase_start_date <= now < phase_end_date)
	// 2. Have a winner content (winner_content_id IS NOT NULL)
	// 3. Don't already have a Matrix room
	err := db.Raw(`
		SELECT mcc.* FROM movie_club_cycles mcc
		WHERE mcc.phase = ?
		AND mcc.phase_start_date <= ?
		AND mcc.phase_end_date > ?
		AND mcc.winner_content_id IS NOT NULL
		AND mcc.id NOT IN (
			SELECT DISTINCT mr.cycle_id 
			FROM matrix_rooms mr 
			WHERE mr.cycle_id = mcc.id
		)
		ORDER BY mcc.phase_start_date ASC
	`, PHASE_WATCHING, now, now).Scan(&cycles).Error

	if err != nil {
		return nil, fmt.Errorf("failed to get active watching cycles without rooms: %w", err)
	}

	// Preload the winner content for each cycle
	for i := range cycles {
		if err := db.Preload("WinnerContent").Find(&cycles[i], cycles[i].ID).Error; err != nil {
			slog.Warn("Failed to preload winner content for cycle", 
				"cycle_id", cycles[i].ID, 
				"error", err)
		}
	}

	return cycles, nil
}

// CreateRoomsForExistingCycles creates Matrix rooms for active watching cycles that don't have them
func CreateRoomsForExistingCycles(db *gorm.DB) (*RetroactiveRoomCreationResult, error) {
	if !Config.MOVIE_CLUB.Matrix.Enabled {
		return nil, errors.New("matrix integration is not enabled")
	}

	if matrixClient == nil {
		return nil, errors.New("matrix client not initialized")
	}

	// Get cycles that need rooms
	cycles, err := GetActiveWatchingCyclesWithoutRooms(db)
	if err != nil {
		return nil, fmt.Errorf("failed to get cycles needing rooms: %w", err)
	}

	result := &RetroactiveRoomCreationResult{
		TotalCycles:    len(cycles),
		CreatedRooms:   0,
		FailedRooms:    0,
		CreatedRoomIDs: make([]string, 0),
		Errors:         make([]string, 0),
	}

	if len(cycles) == 0 {
		slog.Info("No active watching cycles found that need Matrix rooms")
		return result, nil
	}

	slog.Info("Creating Matrix rooms for existing watching cycles", 
		"cycle_count", len(cycles))

	// Create spaces and rooms for each cycle using the new space-based architecture
	for _, cycle := range cycles {
		var movieTitle string
		if cycle.WinnerContent != nil {
			movieTitle = cycle.WinnerContent.Title
		} else {
			movieTitle = fmt.Sprintf("Cycle %d", cycle.ID)
		}
		
		slog.Info("Creating Matrix space and rooms for existing cycle", 
			"cycle_id", cycle.ID,
			"cycle_name", cycle.Name,
			"movie_title", movieTitle)

		// Create cycle space
		cycleSpace, err := CreateCycleSpace(db, &cycle)
		if err != nil {
			errorMsg := fmt.Sprintf("Failed to create space for cycle %d (%s): %v", 
				cycle.ID, cycle.Name, err)
			slog.Error("Retroactive space creation failed", 
				"cycle_id", cycle.ID,
				"cycle_name", cycle.Name,
				"error", err)
			
			result.FailedRooms++
			result.Errors = append(result.Errors, errorMsg)
			continue
		}

		// Ensure Movie Club space exists and add cycle space to hierarchy
		movieClubSpace, err := EnsureMovieClubSpace(db)
		if err != nil {
			slog.Error("Failed to ensure Movie Club space", "error", err, "cycle_id", cycle.ID)
		} else {
			if err := SetupSpaceHierarchy(db, movieClubSpace, cycleSpace); err != nil {
				slog.Error("Failed to setup space hierarchy for cycle", "error", err, "cycle_id", cycle.ID, "space_id", cycleSpace.SpaceID)
			}
		}

		// Create General and Spoilers rooms in the cycle space
		if err := CreateCycleRooms(db, cycleSpace, &cycle); err != nil {
			errorMsg := fmt.Sprintf("Failed to create rooms for cycle %d (%s): %v", 
				cycle.ID, cycle.Name, err)
			slog.Error("Failed to create cycle rooms", "error", err, "cycle_id", cycle.ID, "space_id", cycleSpace.SpaceID)
			
			result.FailedRooms++
			result.Errors = append(result.Errors, errorMsg)
			continue
		}

		// Count both General and Spoilers rooms as created
		result.CreatedRooms += 2 // General + Spoilers
		
		// Get the created rooms to add their IDs to result
		var createdRooms []MatrixRoom
		if err := db.Where("space_id = ?", cycleSpace.SpaceID).Find(&createdRooms).Error; err == nil {
			for _, room := range createdRooms {
				result.CreatedRoomIDs = append(result.CreatedRoomIDs, room.RoomID)
			}
		}
		
		slog.Info("Successfully created Matrix space and rooms for existing cycle",
			"cycle_id", cycle.ID,
			"cycle_name", cycle.Name,
			"space_id", cycleSpace.SpaceID,
			"movie_title", movieTitle)
	}

	slog.Info("Retroactive room creation completed",
		"total_cycles", result.TotalCycles,
		"created_rooms", result.CreatedRooms,
		"failed_rooms", result.FailedRooms)

	return result, nil
}

// RetroactiveRoomCreationResult represents the result of creating rooms for existing cycles
type RetroactiveRoomCreationResult struct {
	TotalCycles    int      `json:"totalCycles"`
	CreatedRooms   int      `json:"createdRooms"`
	FailedRooms    int      `json:"failedRooms"`
	CreatedRoomIDs []string `json:"createdRoomIds"`
	Errors         []string `json:"errors"`
}

// Utility functions

// generateRoomAlias creates a Matrix room alias for a cycle
func generateRoomAlias(cycle *MovieClubCycle) string {
	// Format: movieclub-YYYY-MM-DD-normalized-title
	dateStr := cycle.VotingEndDate.Format("2006-01-02")
	
	var title string
	if cycle.WinnerContent != nil {
		title = cycle.WinnerContent.Title
	} else {
		// Fallback if winner content is not loaded
		title = fmt.Sprintf("cycle-%d", cycle.ID)
	}
	
	normalizedTitle := normalizeTitle(title)
	return fmt.Sprintf("movieclub-%s-%s", dateStr, normalizedTitle)
}

// normalizeTitle normalizes a movie title for use in Matrix room alias
func normalizeTitle(title string) string {
	// Convert to lowercase and replace non-alphanumeric characters with hyphens
	normalized := strings.ToLower(title)
	
	// Replace multiple spaces and special characters with single hyphen
	var result strings.Builder
	lastWasHyphen := false
	
	for _, r := range normalized {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			result.WriteRune(r)
			lastWasHyphen = false
		} else if !lastWasHyphen {
			result.WriteRune('-')
			lastWasHyphen = true
		}
	}
	
	// Remove trailing hyphen if present
	finalResult := strings.TrimSuffix(result.String(), "-")
	
	// Limit length to 50 characters to avoid Matrix alias length limits
	if len(finalResult) > 50 {
		finalResult = finalResult[:50]
		// Remove trailing hyphen that might have been created by truncation
		finalResult = strings.TrimSuffix(finalResult, "-")
	}
	
	return finalResult
}

