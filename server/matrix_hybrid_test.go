func TestMigrateSingleMatrixUserToV2(t *testing.T) {
	db := setupTestDB(t)
	initializeEncryptionKey()
	
	user := setupTestUser(t, db, "testuser")

	// Create legacy user
	legacyUser := &MatrixUser{
		UserID:              user.ID,
		MatrixUserID:        "@watcharr_123_testuser:test.example.com",
		IsAutoGenerated:     true,
		AccessToken:         "encrypted-token",
		DeviceID:            "test-device",
		PasswordExported:    false,
		PasswordExportCount: 0,
	}
	
	err := db.Create(legacyUser).Error
	require.NoError(t, err, "Should create legacy user")

	// Test single user migration
	err = MigrateSingleMatrixUserToV2(db, user.ID)
	assert.NoError(t, err, "Single user migration should succeed")

	// Verify V2 user was created
	var v2User MatrixUserV2
	err = db.Where("user_id = ?", user.ID).First(&v2User).Error
	assert.NoError(t, err, "Should find migrated V2 user")

	assert.Equal(t, AccountTypePersonal, v2User.AccountType, "Should be personal account")
	assert.Equal(t, legacyUser.MatrixUserID, v2User.MatrixUserID, "Should preserve Matrix user ID")
	assert.Equal(t, legacyUser.AccessToken, v2User.AccessToken, "Should preserve access token")

	// Verify legacy user is soft deleted
	var deletedLegacyUser MatrixUser
	err = db.Where("user_id = ?", user.ID).First(&deletedLegacyUser).Error
	assert.Error(t, err, "Legacy user should be soft deleted")

	// Test migration of non-existent user
	err = MigrateSingleMatrixUserToV2(db, 999)
	assert.Error(t, err, "Should return error for non-existent user")
	assert.Contains(t, err.Error(), "no legacy Matrix account found", "Error should mention no account found")

	// Create a new user for testing existing V2 account scenario
	user2 := setupTestUser(t, db, "testuser2")
	
	// Create both a legacy account and a V2 account for user2 to simulate the conflict
	legacyUser2 := &MatrixUser{
		UserID:              user2.ID,
		MatrixUserID:        "@watcharr_789_testuser2:test.example.com",
		IsAutoGenerated:     true,
		AccessToken:         "encrypted-token-2",
		DeviceID:            "test-device-2",
		PasswordExported:    false,
		PasswordExportCount: 0,
	}
	err = db.Create(legacyUser2).Error
	require.NoError(t, err, "Should create legacy user for test")
	
	// Create a V2 account for user2 directly to create conflict
	existingV2User2 := &MatrixUserV2{
		UserID:          user2.ID,
		MatrixUserID:    "@watcharr_456_testuser2:test.example.com",
		AccountType:     AccountTypePersonal,
		IsAutoGenerated: true,
		ASManagedUser:   false,
		CreatedViaAS:    false,
		LastSeenAt:      time.Now(),
	}
	err = db.Create(existingV2User2).Error
	require.NoError(t, err, "Should create existing V2 user for test")
	
	// Test migration of user that already has V2 account
	err = MigrateSingleMatrixUserToV2(db, user2.ID)
	assert.Error(t, err, "Should return error for user with existing V2 account")
	assert.Contains(t, err.Error(), "already has a V2 Matrix account", "Error should mention existing V2 account")
}

