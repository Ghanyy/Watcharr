func TestMigrateMatrixUsersToV2(t *testing.T) {
	db := setupTestDB(t)
	
	// Initialize encryption for password handling
	initializeEncryptionKey()
	
	// Create test users
	user1 := setupTestUser(t, db, "user1")
	user2 := setupTestUser(t, db, "user2")
	user3 := setupTestUser(t, db, "user3")

	// Create legacy Matrix users
	legacyUsers := []*MatrixUser{
		{
			UserID:              user1.ID,
			MatrixUserID:        "@watcharr_1_user1:test.example.com",
			IsAutoGenerated:     true,
			AccessToken:         "encrypted-token-1",
			DeviceID:            "device-1",
			PasswordExported:    false,
			PasswordExportCount: 0,
		},
		{
			UserID:              user2.ID,
			MatrixUserID:        "@watcharr_2_user2:test.example.com",
			IsAutoGenerated:     false, // Custom account
			AccessToken:         "encrypted-token-2",
			DeviceID:            "device-2",
			PasswordExported:    true,
			PasswordExportCount: 2,
		},
	}

	for _, user := range legacyUsers {
		err := db.Create(user).Error
		require.NoError(t, err, "Should create legacy user")
	}
	
	// Fix user2 to have IsAutoGenerated=false (GORM default overrides it)
	err := db.Model(&MatrixUser{}).Where("user_id = ?", user2.ID).Update("is_auto_generated", false).Error
	require.NoError(t, err, "Should update user2 IsAutoGenerated")
	
	// Verify the data is correctly set
	var stored MatrixUser
	err = db.Where("user_id = ?", user2.ID).First(&stored).Error
	require.NoError(t, err, "Should find user2")
	require.False(t, stored.IsAutoGenerated, "User2 should have IsAutoGenerated=false")

	// Create one V2 user that already exists (should be skipped)
	existingV2User := &MatrixUserV2{
		UserID:          user3.ID,
		MatrixUserID:    "@watcharr_3_user3:test.example.com",
		AccountType:     AccountTypePersonal,
		IsAutoGenerated: true,
		ASManagedUser:   false,
		CreatedViaAS:    false,
		LastSeenAt:      time.Now(),
	}
	err = db.Create(existingV2User).Error
	require.NoError(t, err, "Should create existing V2 user")

	// Run migration
	result, err := MigrateMatrixUsersToV2(db)
	require.NoError(t, err, "Migration should succeed")

	// Verify migration results
	assert.Equal(t, 2, result.TotalLegacyUsers, "Should find 2 legacy users")
	assert.Equal(t, 2, result.MigratedUsers, "Should migrate 2 users")
	assert.Equal(t, 0, result.FailedMigrations, "Should have no failures")
	assert.Equal(t, 0, result.SkippedUsers, "Should have no skipped users")
	assert.Len(t, result.MigratedUserIDs, 2, "Should have 2 migrated user IDs")
	assert.Empty(t, result.Errors, "Should have no errors")

	// Verify V2 users were created
	var v2Users []MatrixUserV2
	err = db.Find(&v2Users).Error
	require.NoError(t, err, "Should find V2 users")
	assert.Len(t, v2Users, 3, "Should have 3 V2 users (2 migrated + 1 existing)")

	// Verify migrated user properties
	for _, v2User := range v2Users {
		if v2User.UserID == user1.ID {
			assert.Equal(t, AccountTypePersonal, v2User.AccountType, "Should be personal account")
			assert.True(t, v2User.IsAutoGenerated, "Should preserve auto generated flag")
			assert.False(t, v2User.ASManagedUser, "Should not be AS managed")
			assert.False(t, v2User.CreatedViaAS, "Should not be created via AS")
			assert.Equal(t, "encrypted-token-1", v2User.AccessToken, "Should preserve access token")
		} else if v2User.UserID == user2.ID {
			assert.Equal(t, AccountTypePersonal, v2User.AccountType, "Should be personal account")
			assert.False(t, v2User.IsAutoGenerated, "Should preserve auto generated flag")
			assert.True(t, v2User.PasswordExported, "Should preserve password exported flag")
			assert.Equal(t, 2, v2User.PasswordExportCount, "Should preserve export count")
		}
	}

	// Verify legacy users are soft deleted
	var legacyCount int64
	err = db.Model(&MatrixUser{}).Count(&legacyCount).Error
	require.NoError(t, err, "Should count legacy users")
	assert.Equal(t, int64(0), legacyCount, "Legacy users should be soft deleted")

	// Verify legacy users exist with Unscoped
	err = db.Unscoped().Model(&MatrixUser{}).Count(&legacyCount).Error
	require.NoError(t, err, "Should count unscoped legacy users")
	assert.Equal(t, int64(2), legacyCount, "Legacy users should exist in soft deleted state")
}

